"""Writes libcuda/yasai_cudart_gap.cc: CUDA runtime entry points that a program linked against the
shared runtime may reference but the simulator does not implement (the list in
yasai_cudart_gap.txt: the cuda* symbols that cuda-bindings 13.4.4's runtime extensions reference,
minus the ones libcudart.so of the simulator defines).

  python3 gen_cudart_gap.py yasai_cudart_gap.txt <defined symbols of libcudart.so> > yasai_cudart_gap.cc

Per name:
  * <base>_ptds / <base>_ptsz whose <base> the simulator defines: a forwarder that jumps to <base>
    with the caller's arguments (the simulator has one default stream behavior);
  * any other name: a stub that warns once and returns cudaErrorNotSupported (801).
"""
import sys


def main():
    """Prints the generated C++ file."""
    gap = [l.strip() for l in open(sys.argv[1]) if l.strip() and not l.startswith("#")]
    defined = {l.strip() for l in open(sys.argv[2]) if l.strip()}
    out = ["// yasai: generated by gen_cudart_gap.py from yasai_cudart_gap.txt; do not edit.",
           "// CUDA runtime entry points that the simulator does not implement, so that a program linked",
           "// against the shared runtime (cuda-bindings rebuilt with libcudart.so) loads: per-thread",
           "// default stream variants forward to the simulator's function, the others answer",
           "// cudaErrorNotSupported after a one-time warning.",
           "#include <cstdio>",
           "",
           "namespace {",
           "/// Prints a one-time warning for an entry point that is not simulated.",
           "/// @param name Function name.",
           "/// @param warned Per-function flag.",
           "void yasai_gap_warn(const char *name, bool *warned) {",
           "  if (*warned) return;",
           "  *warned = true;",
           "  fprintf(stderr, \"GPGPU-Sim: %s is not simulated (cudaErrorNotSupported)\\n\", name);",
           "}",
           "}  // namespace",
           "",
           "extern \"C\" {"]
    for n in gap:
        base = n[:-5] if n.endswith("_ptds") or n.endswith("_ptsz") else None
        if base and base in defined:
            out += [f"/// {n}: forwards to {base} (arguments untouched).",
                    f"__attribute__((naked, visibility(\"default\"))) void {n}() {{",
                    f"  __asm__ volatile(\"jmp {base}@PLT\");",
                    "}"]
        else:
            out += [f"/// {n}: not simulated.",
                    f"__attribute__((visibility(\"default\"))) int {n}(...) {{",
                    "  static bool warned = false;",
                    f"  yasai_gap_warn(\"{n}\", &warned);",
                    "  return 801;",
                    "}"]
    out += ["}  // extern \"C\"", ""]
    print("\n".join(out))


main()
